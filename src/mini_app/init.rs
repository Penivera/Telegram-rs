//! Cryptographic validation and parsing for Telegram Mini App `initData`.
//!
//! Telegram Mini Apps transmit authentication launch data to the client via `Telegram.WebApp.initData`.
//! This module provides parsing and HMAC-SHA256 signature verification to validate that the launch
//! data originates from Telegram and has not been tampered with.
//!
//! ### Verification Algorithm
//!
//! 1. Parses raw query string parameters and removes the `hash` parameter.
//! 2. Sorts remaining key-value pairs alphabetically and joins them with `\n` to form the `data_check_string`.
//! 3. Generates a secret key using `HMAC-SHA256("WebAppData", bot_token)`.
//! 4. Calculates `HMAC-SHA256(secret_key, data_check_string)` and verifies it against the received hex hash.
//! 5. Validates timestamp freshness to prevent replay attacks.

use crate::Error;
use crate::Result;
use hex;
use hmac::{Hmac, Mac};
use serde::{Deserialize, Serialize};
use sha2::Sha256;
use std::collections::BTreeMap;
use std::time::{SystemTime, UNIX_EPOCH};

type HmacSha256 = Hmac<Sha256>;

/// Parsed and validated Telegram Mini App launch data.
///
/// Contains user metadata, authentication timestamp, and query parameters.
///
/// # Examples
///
/// ```
/// use telegram_rs_2::mini_app::InitData;
///
/// let raw = "query_id=test&auth_date=1700000000&hash=mock_hash";
/// let init_data = InitData::parse(raw).expect("Parsing failed");
/// assert_eq!(init_data.query_id.as_deref(), Some("test"));
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InitData {
    /// A unique identifier for the Web App session, passed when opened from an inline query.
    pub query_id: Option<String>,

    /// Information about the current Telegram user who launched the Mini App.
    pub user: Option<UserData>,

    /// Unix timestamp when the launch data was generated by Telegram.
    pub auth_date: i64,

    /// Hexadecimal HMAC-SHA256 signature generated by Telegram.
    pub hash: String,

    /// Sorted raw key-value pairs used for cryptographic signature reconstruction.
    #[serde(skip)]
    raw_pairs: BTreeMap<String, String>,
}

/// User details extracted from the `user` field of Mini App `initData`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UserData {
    /// A unique identifier for the user or bot.
    pub id: i64,

    /// `true`, if this user is a bot.
    pub is_bot: Option<bool>,

    /// First name of the user or bot.
    pub first_name: String,

    /// Last name of the user or bot.
    pub last_name: Option<String>,

    /// Username of the user or bot.
    pub username: Option<String>,

    /// [IETF language tag](https://en.wikipedia.org/wiki/IETF_language_tag) of the user's client language.
    pub language_code: Option<String>,
}

impl InitData {
    /// Parses an `initData` query string into an [`InitData`] struct.
    ///
    /// # Arguments
    /// * `raw_data` - The raw query string, e.g. `"query_id=...&user=...&auth_date=...&hash=..."`.
    ///
    /// # Errors
    /// Returns [`Error::Other`] if the query string is missing required fields (`hash`, `auth_date`).
    pub fn parse(raw_data: &str) -> Result<Self> {
        let mut map = BTreeMap::new();
        // Manual parsing to handle URL decoding correctly
        for pair in raw_data.split('&') {
            let mut parts = pair.splitn(2, '=');
            if let (Some(key), Some(value)) = (parts.next(), parts.next()) {
                let decoded_val =
                    urlencoding::decode(value).map_err(|e| Error::Other(e.to_string()))?;
                map.insert(key.to_string(), decoded_val.to_string());
            }
        }

        let hash = map
            .remove("hash")
            .ok_or_else(|| Error::Other("Missing hash parameter".to_owned()))?;

        let user = if let Some(u) = map.get("user") {
            Some(serde_json::from_str(u).map_err(Error::Serialization)?)
        } else {
            None
        };

        let query_id = map.get("query_id").cloned();
        let auth_date = map
            .get("auth_date")
            .ok_or_else(|| Error::Other("Missing auth_date parameter".to_owned()))?
            .parse::<i64>()
            .map_err(|_| Error::Other("Invalid auth_date format".to_owned()))?;

        Ok(Self {
            query_id,
            user,
            auth_date,
            hash,
            raw_pairs: map,
        })
    }

    /// Verifies the cryptographic HMAC-SHA256 signature using your bot token.
    ///
    /// # Arguments
    /// * `bot_token` - The Telegram bot token obtained from `@BotFather`.
    ///
    /// # Returns
    /// * `Ok(true)` if the calculated signature matches `hash`.
    /// * `Ok(false)` if the signature does not match (data was modified or forged).
    ///
    /// # Errors
    /// Returns [`Error::Other`] if the HMAC key calculation encounters an internal error.
    pub fn validate(&self, bot_token: &str) -> Result<bool> {
        // 1. Create data check string (key=value joined by \n in alphabetical key order)
        let data_check_string = self
            .raw_pairs
            .iter()
            .map(|(k, v)| format!("{}={}", k, v))
            .collect::<Vec<_>>()
            .join("\n");

        // 2. Calculate secret key: HMAC-SHA256("WebAppData", bot_token)
        let mut mac = HmacSha256::new_from_slice(b"WebAppData")
            .map_err(|_| Error::Other("HMAC initialization error".into()))?;
        mac.update(bot_token.as_bytes());
        let secret_key = mac.finalize().into_bytes();

        // 3. Calculate hash: HMAC-SHA256(secret_key, data_check_string)
        let mut mac = HmacSha256::new_from_slice(&secret_key)
            .map_err(|_| Error::Other("HMAC signature error".into()))?;
        mac.update(data_check_string.as_bytes());
        let calculated_hash = hex::encode(mac.finalize().into_bytes());

        // 4. Compare calculated hash with the provided signature
        Ok(calculated_hash == self.hash)
    }

    /// Returns a reference to the parsed [`UserData`], if present in the launch data.
    pub fn user(&self) -> Option<&UserData> {
        self.user.as_ref()
    }

    /// Validates that the authentication timestamp is not older than `valid_seconds`.
    ///
    /// Includes a 30-second clock skew tolerance for future timestamps.
    ///
    /// # Arguments
    /// * `valid_seconds` - Allowed lifespan of the launch data (typically 300 to 86400 seconds).
    pub fn is_valid_timestamp(&self, valid_seconds: u64) -> bool {
        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs() as i64;

        // Valid if auth_date is not in future (with 30s leeway) and not older than valid_seconds
        self.auth_date <= now + 30 && self.auth_date >= now - (valid_seconds as i64)
    }
}
